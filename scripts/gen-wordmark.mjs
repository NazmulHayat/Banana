// Build-time generator: bakes the "Aight Bet" wordmark into per-letter SVG
// paths (Shantell Sans Medium) with exact path lengths, so the splash can
// animate a true pen-trace handwriting effect at runtime.
//
//   node scripts/gen-wordmark.mjs
//
// Output: constants/wordmark-paths.ts (committed, regenerate if the name
// or font changes).

import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";
import { svgPathProperties as SvgPathProperties } from "svg-path-properties";

const TEXT = "Aight Bet";
const FONT_SIZE = 64;
const FONT_FILE =
  "node_modules/@expo-google-fonts/shantell-sans/500Medium/ShantellSans_500Medium.ttf";

const buf = readFileSync(FONT_FILE);
const font = opentype.parse(
  buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength),
);

const ascent = (font.ascender / font.unitsPerEm) * FONT_SIZE;
const descent = Math.abs((font.descender / font.unitsPerEm) * FONT_SIZE);
const height = Math.ceil(ascent + descent);

let x = 2;
const letters = [];
for (const char of TEXT) {
  const glyph = font.charToGlyph(char);
  const advance = (glyph.advanceWidth / font.unitsPerEm) * FONT_SIZE;
  if (char !== " ") {
    const path = font.getPath(char, x, ascent, FONT_SIZE);
    const d = path.toPathData(2);
    const length = Math.ceil(new SvgPathProperties(d).getTotalLength());
    letters.push({ char, d, length });
  }
  x += advance;
}
const width = Math.ceil(x + 2);

const ts = `// AUTO-GENERATED by scripts/gen-wordmark.mjs — do not edit by hand.
// "${TEXT}" in Shantell Sans Medium, baked to SVG paths for the pen-trace
// handwriting animation. Regenerate if the name or font changes.

export interface WordmarkLetter {
  char: string;
  /** SVG path data for this letter's outline. */
  d: string;
  /** Exact outline length, for strokeDasharray tracing. */
  length: number;
}

export const WORDMARK_W = ${width};
export const WORDMARK_H = ${height};

export const WORDMARK_LETTERS: WordmarkLetter[] = ${JSON.stringify(letters, null, 2)};
`;

writeFileSync("constants/wordmark-paths.ts", ts);
console.log(
  `Wrote constants/wordmark-paths.ts — ${letters.length} letters, viewBox ${width}x${height}`,
);
